/**
 * Build src/brainstorm/kits.js from the local kit markdown.
 * Drops Engine and Doctrine seam lines. Those stay in the gitignored sources.
 */
import { readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const CATEGORIES = [
  ['Problem Solving', 'problem'],
  ['Creative Thinking', 'idea'],
  ['Decision Making', 'decision'],
  ['People Solving', 'person'],
  ['Self-Management', 'ourselves'],
  ['Testing and Learning', 'experiment'],
  ['Systems and Strategy', 'big_picture'],
  ['Meta-Process', 'process'],
]

function field(block, label) {
  const match = block.match(new RegExp(`- \\*\\*${label}:\\*\\*\\s*([\\s\\S]*?)(?=\\n- \\*\\*|$)`))
  return match ? match[1].replace(/\s+/g, ' ').trim() : ''
}

function parseSignature(text) {
  const section = text.split('**Signature kit')[1]?.split('**Entry format**')[0] || ''
  return section.split('\n')
    .map((line) => line.trim())
    .filter((line) => line.startsWith('|') && !line.includes('---'))
    .map((line) => line.split('|')[1]?.trim())
    .filter((name) => name && name !== 'Framework')
}

function parseChallenges(text) {
  const section = text.split(/## Not in /)[1] || ''
  return [...section.matchAll(/\|\s*([^|\n]+?)\s*\|\s*([^|\n]+?)\s*\|/g)]
    .map((match) => ({
      name: match[1].trim(),
      challenge: match[2].trim().replace(/^[A-Z][a-z]+'s seam:\s*/, ''),
    }))
    .filter((row) => row.name && row.name !== 'Framework' && !row.name.startsWith('-'))
}

function parseFrameworks(text, voice) {
  const useLabel = voice === 'ethos' ? 'Ethos use' : 'Ego use'
  const asksLabel = voice === 'ethos' ? 'Ethos asks' : 'Ego asks'
  const divergenceLabel = voice === 'ethos' ? 'Divergence from Ego' : 'Divergence from Ethos'
  const body = text.split(/## Not in /)[0]
  const signature = new Set(parseSignature(text))
  const frameworks = []
  let category = 'problem'
  const headings = [...body.matchAll(/^(#{2,4}) (.+)$/gm)]

  headings.forEach((match, index) => {
    const level = match[1].length
    const headerLine = match[2].trim()
    if (level === 2) {
      const categoryHit = CATEGORIES.find(([label]) => headerLine.includes(label))
      if (categoryHit) category = categoryHit[1]
      return
    }
    if (level === 3 && /^(Understanding|Communicating|Resolving)$/.test(headerLine)) return
    if (level < 3) return

    const start = match.index + match[0].length
    const end = headings[index + 1]?.index ?? body.length
    const name = headerLine.replace(/\s*●\s*/, ' ').replace(/\s*\[Mode-gated\]\s*/, ' ').replace(/\s+/g, ' ').trim()
    const block = body.slice(start, end)
      .replace(/- \*\*Engine:\*\*[\s\S]*?(?=\n- \*\*|\n#{2,4} |$)/g, '')
      .replace(/- \*\*Doctrine seam:\*\*[\s\S]*?(?=\n- \*\*|\n#{2,4} |$)/g, '')
      .replace(/- \*\*Orchestrator note:\*\*[\s\S]*?(?=\n- \*\*|\n#{2,4} |$)/g, '')
    frameworks.push({
      name,
      voice,
      category,
      shared: headerLine.includes('●'),
      modeGated: headerLine.includes('[Mode-gated]'),
      signature: signature.has(name),
      trigger: field(block, 'Trigger'),
      use: field(block, useLabel),
      asks: field(block, asksLabel),
      divergence: field(block, divergenceLabel) || null,
    })
  })

  return { frameworks, challenges: parseChallenges(text), signature: [...signature] }
}

const ethos = parseFrameworks(readFileSync(join(root, 'docs/brainstorm/ethos-problem-solving-frameworks.md'), 'utf8'), 'ethos')
const ego = parseFrameworks(readFileSync(join(root, 'docs/brainstorm/ego-problem-solving-frameworks.md'), 'utf8'), 'ego')

const out = `// Generated by scripts/extract-brainstorm-kits.mjs. Framework catalog only.
export const ethosFrameworks = ${JSON.stringify(ethos.frameworks, null, 2)}

export const egoFrameworks = ${JSON.stringify(ego.frameworks, null, 2)}

export const ethosSignature = ${JSON.stringify(ethos.signature, null, 2)}

export const egoSignature = ${JSON.stringify(ego.signature, null, 2)}

export const ethosChallenges = ${JSON.stringify(ethos.challenges, null, 2)}

export const egoChallenges = ${JSON.stringify(ego.challenges, null, 2)}
`
writeFileSync(join(root, 'src/brainstorm/kits.js'), out)
